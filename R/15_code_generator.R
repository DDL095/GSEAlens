# ggsave("boxplot.png", p, width = 5, height = 5, dpi = 300)
',
    data_literal,
    ordering_block,
    if (isTRUE(use_zero_baseline)) 'y_min <- min(y_min, 0)\ny_max <- max(y_max, 0)' else '# (zero baseline disabled)',
    baseline_block,
    base_size,
    safe_gene,
    safe_expr
  )
}

