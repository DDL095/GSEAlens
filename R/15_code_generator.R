logfc_thresh <- %g
pval_thresh  <- %g

# --- Classify ----------------------------------------------------------------
de_df$gene_upper <- toupper(de_df$gene_symbol)
de_df$is_user     <- de_df$gene_upper %%in%% user_genes
de_df$is_pathway  <- de_df$gene_upper %%in%% pathway_genes
