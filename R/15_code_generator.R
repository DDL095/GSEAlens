'  annotate("text", x = -Inf, y = Inf, color = "#377EB8",\n',
'           label = sprintf("High in %s", "', right_group, '"),\n',
'           hjust = -0.08, vjust = 1.6, fontface = "bold", size = 4.5) +\n',
'  coord_cartesian(clip = "off") +\n',
'  theme(\n',
'    plot.title    = element_text(face = "bold", hjust = 0.5),\n',
