# ggsave("boxplot.png", p, width = %g, height = %g, dpi = %g)

# ggsave("boxplot.svg", p, width = %g, height = %g)

',

    data_literal,

    ordering_block,

    if (isTRUE(use_zero_baseline)) 'y_min <- min(y_min, 0)\ny_max <- max(y_max, 0)' else '# (zero baseline disabled)',

    baseline_block,

    base_size,

    safe_gene,

    safe_expr,

    margin_top, margin_right, margin_bottom, margin_left,

    fig_width, fig_height,

    fig_width, fig_height, fig_dpi,

    fig_width, fig_height

    )

}



