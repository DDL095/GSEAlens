'      sum(de_df$category == "up"),   sum(de_df$category == "down"),\n',
'      sum(de_df$category == "ns"),   sum(de_df$category == "user"),\n',
'      sum(de_df$category == "pathway"), sum(de_df$category == "both")),\n',
'    x = "log2 Fold Change",\n',
