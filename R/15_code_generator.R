#' @title Generate Publication DE Volcano Code
#' @description Return an executable ggplot2 script reproducing the Quadrant
#'   module's gene-level Differential Expression Volcano as a static,
#'   publication-ready figure. Six-color classification (both / user /
#'   pathway / up / down / ns) mirrors the interactive plotly view.
#' @param de_df data.frame with at least: gene_symbol, logFC, pvalue.
#'   Optional columns: padj (for hover annotation only).
#' @param user_genes Character vector of user-selected genes (upper-cased).
#' @param pathway_genes Character vector of pathway genes (upper-cased).
#' @param logfc_thresh Numeric. Default 1.
#' @param pval_thresh Numeric. Default 0.05.
#' @param left_group Character.
#' @param right_group Character.
#' @param base_size Numeric.
#' @return Character scalar of executable R code.
#' @export
generate_de_volcano_code <- function(de_df,
                                     user_genes = character(0),
                                     pathway_genes = character(0),
                                     logfc_thresh = 1,
                                     pval_thresh = 0.05,
                                     left_group = "Left",
                                     right_group = "Right",
                                     show_annotations = FALSE,
                                     base_size = 12) {
  # Subset to essential columns + trim to top-N by significance to keep the
  # generated script readable and runnable. We keep ALL significant points
  # plus a thin slice of NS for visual context.
  keep_cols <- intersect(c("gene_symbol", "logFC", "pvalue", "padj"),
                         colnames(de_df))
  de_subset <- de_df[, keep_cols, drop = FALSE]
  # Cap at 5000 rows to keep dput output manageable for clipboard copy.
  if (nrow(de_subset) > 5000) {
    sig_mask <- !is.na(de_subset$pvalue) & de_subset$pvalue < pval_thresh
    ns_indices <- which(!sig_mask)
    ns_keep <- ns_indices[seq_len(min(length(ns_indices), 2000))]
    sig_indices <- which(sig_mask)
    keep_idx <- sort(c(sig_indices, ns_keep))
    de_subset <- de_subset[keep_idx, , drop = FALSE]
  }
  data_literal <- paste(utils::capture.output(dput(de_subset)), collapse = "\n")
  user_str <- if (length(user_genes) > 0) {
    paste0('c(', paste0('"', user_genes, '"', collapse = ", "), ')')
  } else "character(0)"
