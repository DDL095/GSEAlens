    )
  } else {
    paste0(
'  labs(\n',
'    title = sprintf("DE Volcano: %s vs %s", "', left_group, '", "', right_group, '"),\n',
'    x = "log2 Fold Change",\n',
'    y = "-log10(P-value)"\n',
'  ) +\n',
'  theme(\n',
'    plot.title    = element_text(face = "bold", hjust = 0.5),\n',
'    legend.position = "right"\n',
'  )'
    )
  }

