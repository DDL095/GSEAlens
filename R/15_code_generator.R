#' @param edge_df data.frame with columns: from, to, weight, shared.
#' @param node_df data.frame with columns: name, x, y, NES, p.adjust.
#' @param width_mode Character. "rank" or "weight".
#' @param seed Integer. Layout seed (informational; layout is recomputed
#'   inside the generated script for full reproducibility).
#' @param base_size Numeric.
#' @return Character scalar of executable R code.
#' @export
generate_network_code <- function(edge_df, node_df,
                                  width_mode = "weight",
                                  seed = 42L,
                                  base_size = 12) {
  edge_literal <- paste(utils::capture.output(dput(edge_df)), collapse = "\n")
  node_literal <- paste(utils::capture.output(dput(node_df)), collapse = "\n")
  width_block <- if (width_mode == "rank") {
