de_df$logFC  <- suppressWarnings(as.numeric(de_df$logFC))
de_df$pvalue <- suppressWarnings(as.numeric(de_df$pvalue))
de_df$logFC[is.na(de_df$logFC)]  <- 0
de_df$pvalue[is.na(de_df$pvalue)] <- 1

