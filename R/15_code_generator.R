  n <- nrow(edge_df)
  edge_df$width <- 5 - (seq_len(n) - 1) * 4 / max(1, n - 1)
  edge_df$width <- pmax(1, pmin(5, edge_df$width))'
  } else {
'  # weight-based: edge width proportional to Jaccard value (emapplot style)
